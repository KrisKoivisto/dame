#!/usr/bin/env python3
"""Refresh the GAMES block in index.html from ESPN's public schedule and box scores.

Usage: python3 tools/update_games.py [index.html ...]
Hand-written extras (a postgame quote, highlight video ids) live in tools/notes.json keyed by ESPN event id
and are merged in, so a refresh never drops them.
"""
import json, re, sys, urllib.request, pathlib

HERE = pathlib.Path(__file__).resolve().parent
SCHED = 'https://site.api.espn.com/apis/site/v2/sports/basketball/nba/teams/por/schedule'
SUMMARY = 'https://site.api.espn.com/apis/site/v2/sports/basketball/nba/summary?event='
VENUE = {'Mortgage Matchup Center': 'Mortgage Matchup Center', 'crypto.com Arena': 'Crypto.com Arena'}
NAMES = {'UTAH': 'Jazz', 'SA': 'Spurs', 'GS': 'Warriors', 'NO': 'Pelicans', 'NY': 'Knicks', 'WSH': 'Wizards', 'LAL': 'Lakers', 'LAC': 'Clippers'}

def get(url):
    with urllib.request.urlopen(url, timeout=30) as r: return json.load(r)

def score(t):
    s = t.get('score'); return int(s['displayValue']) if isinstance(s, dict) else int(s or 0)

def dame_line(event_id):
    s = get(SUMMARY + event_id)
    for tm in s.get('boxscore', {}).get('players', []):
        for st in tm['statistics']:
            for a in st['athletes']:
                if 'Lillard' not in a['athlete']['displayName']: continue
                if a.get('didNotPlay') or not a['stats']: return None, (a.get('reason') or 'Did not play')
                x = dict(zip(st['names'], a['stats']))
                fg, tp, ft = (x[k].split('-') for k in ('FG', '3PT', 'FT'))
                return {'min': int(x['MIN']), 'pts': int(x['PTS']), 'reb': int(x['REB']), 'ast': int(x['AST']), 'fgm': int(fg[0]), 'fga': int(fg[1]),
                        'tpm': int(tp[0]), 'tpa': int(tp[1]), 'ftm': int(ft[0]), 'fta': int(ft[1]), 'pm': int(x['+/-'].replace('+', ''))}, None
    return None, 'Did not play'

def build():
    cache_p = HERE / 'games.json'
    cache = {g['id']: g for g in json.load(open(cache_p))} if cache_p.exists() else {}
    notes = json.load(open(HERE / 'notes.json')) if (HERE / 'notes.json').exists() else {}
    games = []
    for e in get(SCHED)['events']:
        c = e['competitions'][0]; st = c['status']['type']['state']
        por = [t for t in c['competitors'] if t['team']['abbreviation'] == 'POR'][0]
        opp = [t for t in c['competitors'] if t['team']['abbreviation'] != 'POR'][0]
        ab = opp['team']['abbreviation']
        g = {'id': e['id'], 'd': e['date'], 'opp': NAMES.get(ab) or opp['team'].get('shortDisplayName') or opp['team']['displayName'], 'ab': 'UTA' if ab == 'UTAH' else ab,
             'home': por['homeAway'] == 'home', 'at': VENUE.get(c.get('venue', {}).get('fullName'), c.get('venue', {}).get('fullName', '')),
             'tv': ' · '.join([b['media']['shortName'] for b in c.get('broadcasts', []) if b.get('media') and 'League Pass' not in b['media']['shortName']][:2])}
        if st == 'post':
            old = cache.get(e['id'])
            if old and old.get('r'):
                g['r'], g['s'], g['dnp'] = old['r'], old.get('s'), old.get('dnp')
            else:
                g['r'] = [score(por), score(opp)]
                g['s'], g['dnp'] = dame_line(e['id'])
        g.update(notes.get(e['id'], {}))
        games.append(g)
    json.dump(games, open(cache_p, 'w'), indent=1)
    return games

def js(games):
    def lit(g):
        parts = ["d: '%s'" % g['d'], "opp: '%s'" % g['opp'], "ab: '%s'" % g['ab']]
        if g['home']: parts.append('home: 1')
        parts += ["at: '%s'" % g['at'].replace("'", "\\'"), "tv: '%s'" % g['tv'].replace("'", "\\'")]
        if g.get('r'):
            parts.append('r: [%d, %d]' % tuple(g['r']))
            if g.get('s'):
                s = g['s']; parts.append('s: { ' + ', '.join('%s: %d' % (k, s[k]) for k in ('min', 'pts', 'reb', 'ast', 'fgm', 'fga', 'tpm', 'tpa', 'ftm', 'fta', 'pm')) + ' }')
            else:
                parts.append("dnp: '%s'" % (g.get('dnp') or 'Did not play').replace("'", "\\'"))
        if g.get('note'): parts.append('note: ' + json.dumps(g['note'], ensure_ascii=False).replace('"', "'"))
        if g.get('vid'): parts.append('vid: ' + json.dumps(g['vid']).replace('"', "'"))
        return '    { ' + ', '.join(parts) + ' }'
    return '  // GAMES:start (generated by tools/update_games.py; edit tools/notes.json for quotes and videos)\n  var GAMES = [\n' + ',\n'.join(lit(g) for g in games) + '\n  ];\n  // GAMES:end\n'

def patch(path, block):
    s = open(path).read()
    m = re.search(r'  // GAMES:start.*?  // GAMES:end\n', s, re.S) or re.search(r'  var GAMES = \[\n.*?\n  \];\n', s, re.S)
    if not m: raise SystemExit('no GAMES block in ' + path)
    open(path, 'w').write(s[:m.start()] + block + s[m.end():])

if __name__ == '__main__':
    games = build(); block = js(games)
    for p in (sys.argv[1:] or [str(HERE.parent / 'index.html')]): patch(p, block); print('patched', p)
    done = [g for g in games if g.get('r')]
    print('%d games, %d final; last: %s %s %s' % (len(games), len(done), done[-1]['d'][:10], done[-1]['r'], done[-1].get('s') and done[-1]['s']['pts']) if done else 'no finals yet')
